def render_text(text: str, dotpanel_root_str: str, sync_command: str = "dotpanel sync") -> str:
    """Render template placeholders.

    Substitutes {{DOTPANEL_ROOT}} and {{SYNC_COMMAND}} (EC-7). Unknown
    {{...}} tokens emit a warning to stderr (does not error).
    """
    for match in re.finditer(r"\{\{([A-Z_][A-Z0-9_]*)\}\}", text):
        token = match.group(1)
        if token not in KNOWN_PLACEHOLDERS:
            print(f"WARN  unknown template placeholder: {{{{{token}}}}}", file=sys.stderr)
    out = text.replace("{{DOTPANEL_ROOT}}", dotpanel_root_str)
    out = out.replace("{{SYNC_COMMAND}}", sync_command)
    return out


def render_file(template_path: Path, output_path: Path, dotpanel_root_str: str,
                dry_run: bool = False, sync_command: str = "dotpanel sync") -> str:
    """Render a template file. Returns 'wrote', 'noop', or 'would'."""
    rendered = render_text(template_path.read_text(encoding="utf-8"), dotpanel_root_str, sync_command)
    if output_path.exists() and output_path.read_text(encoding="utf-8") == rendered:
        return "noop"
    if dry_run:
        return "would"
    output_path.parent.mkdir(parents=True, exist_ok=True)
    _write_atomic(output_path, rendered)
    return "wrote"


def _write_atomic(path: Path, content: str, *, executable: bool = False) -> None:
    """Per-file transactional write: render to temp file in same dir, then atomic rename.

    Pass `executable=True` to set mode 0o755 after the write (for shebang scripts
    like harness statusline templates that need the executable bit preserved).
    Without it, mkstemp's default 0o600 sticks — which is right for config files
    but wrong for scripts invoked by external harness clients.
    """
    fd, tmp = tempfile.mkstemp(prefix=f".{path.name}.", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(content)
        os.replace(tmp, path)
        if executable:
            os.chmod(path, 0o755)
    except Exception:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


