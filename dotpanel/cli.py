@dataclass(frozen=True)
class SubstrateSkill:
    """A skill discovered from <substrate>/skills/*.md.

    Frontmatter-driven: name + description + supported_harnesses come from the
    file's YAML front matter. Substrate skills override public skills of the
    same name (filename collision = substrate wins, per D7).
    """

    name: str
    body_path: Path
    description: str
    supported_harnesses: tuple[str, ...]


def _parse_skill_frontmatter(path: Path) -> dict[str, Any] | None:
    """Parse the YAML frontmatter of a skill file.

    Returns the parsed dict, or None on malformed/missing frontmatter.
    Emits a WARN (not FAIL) on parse errors per D7 spec — matches Python's
    import-warning model: a broken substrate file should not block configure.
    """
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        print(f"WARN  could not read skill {path}: {exc}", file=sys.stderr)
        return None
    if not text.startswith("---\n"):
        print(f"WARN  skill {path.name} lacks YAML frontmatter; skipping",
              file=sys.stderr)
        return None
    end = text.find("\n---\n", 4)
    if end == -1:
        print(f"WARN  skill {path.name} has unterminated frontmatter; skipping",
              file=sys.stderr)
        return None
    fm_text = text[4:end]
    try:
        # Prefer pyyaml when available — handles complex multiline strings.
        import yaml  # type: ignore[import-not-found]
        data = yaml.safe_load(fm_text)
        if not isinstance(data, dict):
            print(f"WARN  skill {path.name} frontmatter is not a YAML map; skipping",
                  file=sys.stderr)
            return None
        return data
    except ImportError:
        # Minimal fallback: parse top-level `key: value` lines. Sufficient for
        # the documented schema (name, description, supported_harnesses).
        return _minimal_frontmatter_fallback(fm_text, path.name)
    except Exception as exc:
        print(f"WARN  skill {path.name} frontmatter parse failed: {exc}; skipping",
              file=sys.stderr)
        return None


def _minimal_frontmatter_fallback(fm_text: str, filename: str) -> dict[str, Any] | None:
    """Tiny YAML-subset parser for fallback when pyyaml is absent.

    Supports:
      key: value
      key: [a, b, c]
      key: |
        multi-line block
    """
    data: dict[str, Any] = {}
    lines = fm_text.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip() or line.startswith("#"):
            i += 1
            continue
        if ":" not in line:
            i += 1
            continue
        key, _, rest = line.partition(":")
        key = key.strip()
        rest = rest.strip()
        if rest.startswith("[") and rest.endswith("]"):
            inner = rest[1:-1]
            data[key] = [s.strip().strip('"').strip("'") for s in inner.split(",") if s.strip()]
        elif rest == "|":
            # Block scalar: gather indented lines below.
            j = i + 1
            block_lines: list[str] = []
            while j < len(lines) and (lines[j].startswith("  ") or not lines[j].strip()):
                block_lines.append(lines[j][2:] if lines[j].startswith("  ") else lines[j])
                j += 1
            data[key] = "\n".join(block_lines).rstrip()
            i = j
            continue
        else:
            data[key] = rest.strip('"').strip("'")
        i += 1
    return data


def _discover_substrate_skills(substrate_skills_dir: Path | None) -> dict[str, SubstrateSkill]:
    """Discover skills under <substrate>/skills/*.md.

    Returns map skill-name -> SubstrateSkill. Malformed files are skipped with
    a WARN. Directory not present -> empty map.
    """
    if substrate_skills_dir is None or not substrate_skills_dir.is_dir():
        return {}
    found: dict[str, SubstrateSkill] = {}
    for child in sorted(substrate_skills_dir.iterdir()):
        if not child.is_file() or child.suffix != ".md":
            continue
        # Filename-derived name. Frontmatter `name` is informational; the
        # filename is the canonical identifier so substrate vs. public
        # collision detection is simple stem-match.
        stem = child.stem
        fm = _parse_skill_frontmatter(child)
        if fm is None:
            continue
        description = str(fm.get("description", "") or "").strip()
        if not description:
            print(f"WARN  skill {child.name} missing 'description' frontmatter; "
                  "rendered slash entry will be empty", file=sys.stderr)
        raw_harnesses = fm.get("supported_harnesses", ["claude", "codex", "kimi"])
        if isinstance(raw_harnesses, str):
            raw_harnesses = [raw_harnesses]
        if not isinstance(raw_harnesses, list):
            raw_harnesses = ["claude", "codex", "kimi"]
        harnesses = tuple(str(h).strip() for h in raw_harnesses if str(h).strip())
        found[stem] = SubstrateSkill(
            name=stem,
            body_path=child.resolve(),
            description=description,
            supported_harnesses=harnesses,
        )
    return found


def skill_wrapper_body(name: str, harness: str, dotpanel_root_str: str,
                       sync_command: str = "dotpanel sync") -> str:
    canonical_rel = f"protocol/skills/{CANONICAL_SKILL_FILES[name]}"
    canonical_abs = f"{dotpanel_root_str}/{canonical_rel}"
    title = SKILL_TITLES[name]
    description = SKILL_DESCRIPTIONS[name]
    invoke = {
        "claude": f"/{name}",
        "codex": f"${name} or the {name} skill selector",
    }[harness]
    surface = f"Thin {harness.capitalize()} skill"

    if name == "review":
        action = (
            "\nParse the user's arguments:"
            f"\n\n- If `--ui` is present, read `{dotpanel_root_str}/protocol/skills/design-audit.md` and execute it."
            f"\n- Otherwise, read `{canonical_abs}` and execute it."
        )
    else:
        action = f"\nRead `{canonical_abs}` and execute its process."

    fm = (
        "---\n"
        f"name: {name}\n"
        f"description: |\n  Use when the user invokes {invoke}. {description} {surface}: delegates to {canonical_abs}.\n"
        "---\n"
    )
    # The `sync` wrapper bakes the substrate-configured sync command into the
    # rendered output (D4 / IC-SS-2). The canonical body at config-sync.md stays
    # methodology-abstract; the concrete command lives only here, in the
    # rendered harness adapter the harness reads at invocation time.
    sync_hint = ""
    if name == "sync":
        sync_hint = (
            f"\n## Configured sync command\n\n"
            f"The substrate's configured sync command is `{sync_command}` "
            f"(from `.dotpanel.toml [harness] sync_command`; defaults to "
            f"`dotpanel sync`). Use this command for `push` / `pull` / `diff` "
            "/ `status` per the canonical body.\n"
        )
    return (
        f"{fm}\n"
        f"{GENERATED_BANNER}\n"
        f"<!-- Source: {canonical_rel} -->\n"
        f"<!-- Update: dotpanel configure --harness {harness} -->\n\n"
        f"# {title}\n\n"
        f"This is a {surface.lower()}. The canonical process lives in `{canonical_abs}`.\n\n"
        "## Action\n"
        f"{action}\n"
        f"{sync_hint}"
    )


def substrate_skill_wrapper_body(skill: SubstrateSkill, harness: str) -> str:
    """Render a skill wrapper for a substrate-discovered skill.

    Substrate skills don't have a hardcoded title/description in cli.py;
    those come from the file's frontmatter. The wrapper points the harness
    at the substrate body file (absolute path baked in at configure time).
    """
    invoke = {
        "claude": f"/{skill.name}",
        "codex": f"${skill.name} or the {skill.name} skill selector",
    }[harness]
    surface = f"Thin {harness.capitalize()} skill"
    canonical_abs = str(skill.body_path)
    title = skill.name.replace("-", " ").replace("_", " ").title()
    description = skill.description or (
        f"Substrate-private skill (frontmatter description missing in {skill.body_path.name})"
    )
    fm = (
        "---\n"
        f"name: {skill.name}\n"
        f"description: |\n  Use when the user invokes {invoke}. {description} {surface}: delegates to {canonical_abs}.\n"
        "---\n"
    )
    return (
        f"{fm}\n"
        f"{GENERATED_BANNER}\n"
        f"<!-- Source (substrate): {canonical_abs} -->\n"
        f"<!-- Update: dotpanel configure --harness {harness} -->\n\n"
        f"# {title}\n\n"
        f"This is a {surface.lower()}. The canonical process lives in "
        f"`{canonical_abs}`.\n\n"
        "## Action\n"
        f"\nRead `{canonical_abs}` and execute its process.\n"
    )


