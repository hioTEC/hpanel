@dataclass
class ConfigureResult:
    actions: list[str] = field(default_factory=list)
    conflicts: list[str] = field(default_factory=list)


def _excluded_path(rel_path: str, harness: str) -> bool:
    excluded = {
        "claude": CLAUDE_EXCLUDED,
        "codex": CODEX_EXCLUDED,
        "kimi": KIMI_EXCLUDED,
    }[harness]
    head = rel_path.split("/", 1)[0]
    if head in excluded:
        return True
    if harness == "codex":
        for glob in CODEX_EXCLUDED_GLOBS:
            if Path(rel_path).match(glob):
                return True
    return False


def _configure_one_file(rel_path: str, content: str, output_root: Path, harness: str,
                        force: bool, dry_run: bool, home: Path,
                        result: ConfigureResult) -> None:
    """Write rel_path under output_root, respecting banner/conflict rules."""
    target = output_root / rel_path
    excluded_rel = rel_path
    if harness == "codex" and rel_path.startswith("skills/"):
        agents_root = home / ".agents"
        if output_root != home / ".codex":
            agents_root = output_root.parent / "agents"
        target = agents_root / rel_path
        excluded_rel = f".agents/{rel_path}"
    if _excluded_path(excluded_rel, harness):
        return  # Never write to excluded paths
    if target.exists():
        if target.is_symlink():
            link_target = target.resolve()
            if str(link_target).startswith(str(dotpanel_root())):
                # legacy symlink into dotpanel — replace
                action = f"REPLACE-LINK {target}"
                if not dry_run:
                    target.unlink()
                    _write_atomic(target, content) if not _is_json(rel_path) else _write_atomic(target, content)
                result.actions.append(action)
                return
            if not force:
                result.conflicts.append(f"symlink to external target: {target} -> {link_target}")
                return
        elif target.is_file():
            if _is_json(rel_path):
                if is_managed_json(target, home) or force:
                    action = f"OVERWRITE-JSON {target}"
                    if not dry_run:
                        _write_atomic(target, content)
                    result.actions.append(action)
                    return
                result.conflicts.append(f"unmanaged JSON at {target}")
                return
            if has_dotpanel_banner(target):
                if target.read_text(encoding="utf-8") == content:
                    # Content match — but still repair exec-bit drift if the
                    # template is a shebang script and the on-disk file lost
                    # its executable bit (e.g., from earlier write before the
                    # exec-bit fix landed).
                    if content.startswith("#!") and not os.access(target, os.X_OK):
                        if not dry_run:
                            os.chmod(target, 0o755)
                        result.actions.append(f"CHMOD+X {target}")
                    return  # noop on content
                action = f"OVERWRITE {target}"
                if not dry_run:
                    _write_atomic(target, content, executable=content.startswith("#!"))
                result.actions.append(action)
                return
            if force:
                action = f"FORCE {target}"
                if not dry_run:
                    _write_atomic(target, content, executable=content.startswith("#!"))
                result.actions.append(action)
                return
            result.conflicts.append(f"non-banner file at {target}")
            return
    # Target doesn't exist — write
    if dry_run:
        result.actions.append(f"WOULD-CREATE {target}")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        _write_atomic(target, content, executable=content.startswith("#!"))
        result.actions.append(f"CREATE {target}")


def _is_json(rel_path: str) -> bool:
    return rel_path.endswith(".json")


def _gather_outputs(paths: DotpanelPaths, harness: str) -> list[tuple[str, str]]:
    """Returns list of (relative_path, rendered_content) tuples for the harness."""
    root_str = str(paths.root)
    outputs: list[tuple[str, str]] = []
    templates = {
        "claude": paths.claude_templates,
        "codex": paths.codex_templates,
        "kimi": paths.kimi_templates,
    }[harness]
    if not templates.exists():
        return outputs

    # Resolve sync_command from substrate config (D4 / IC-SG-1).
    # `[harness] sync_command` overrides; default is "dotpanel sync".
    substrate = _try_find_substrate()
    sync_command = "dotpanel sync"
    if substrate is not None and substrate.harness is not None:
        sync_command = substrate.harness.sync_command or sync_command

    # Top-level template files (CLAUDE.md / settings.json / statusline.py for claude;
    # AGENTS.md / config.toml for codex)
    for template in templates.iterdir():
        if template.is_file():
            content = render_text(template.read_text(encoding="utf-8"), root_str,
                                  sync_command=sync_command)
            outputs.append((template.name, content))
        elif template.is_dir() and template.name != "skills":
            # statusline.py might live in claude/templates/, copy as-is
            for child in template.rglob("*"):
                if child.is_file():
                    rel = str(child.relative_to(templates))
                    content = render_text(child.read_text(encoding="utf-8"), root_str,
                                          sync_command=sync_command)
                    outputs.append((rel, content))

    # Skill wrappers (programmatically generated, not from template files).
    # Kimi currently discovers shared skills from Claude's skill directory on
    # this setup; do not invent a harness-native skills surface without proof.
    if harness == "kimi":
        return outputs

    # D7: substrate skills override public skills on filename collision; the
    # union of substrate + public (minus substrate-claimed filenames) is the
    # final skill set. `[skills] disabled` list blacklists names from both.
    # Per-skill harness scoping: substrate skills use frontmatter
    # `supported_harnesses`; public skills are configurable via
    # `.dotpanel.toml [skills.<name>] harnesses`.
    substrate_skills_dir = _substrate_skills_dir(substrate)
    substrate_skills = _discover_substrate_skills(substrate_skills_dir)

    disabled: set[str] = set()
    per_skill: dict[str, dict[str, Any]] = {}
    if substrate is not None:
        disabled = set(substrate.skills.disabled)
        per_skill = dict(substrate.skills.per_skill)

    # Substrate skills first (claim filenames).
    for name, skill in substrate_skills.items():
        if name in disabled:
            continue
        if harness not in skill.supported_harnesses:
            continue
        # toml override beats frontmatter for harness scope.
        toml_harnesses = per_skill.get(name, {}).get("harnesses")
        if isinstance(toml_harnesses, list) and harness not in toml_harnesses:
            continue
        rel = f"skills/{name}/SKILL.md"
        content = substrate_skill_wrapper_body(skill, harness)
        outputs.append((rel, content))

    # Public skills: skip any name claimed by substrate.
    for name in USER_FACING_SKILLS:
        if name in disabled:
            continue
        if name in substrate_skills:
            continue
        # toml-level per-skill harness scope.
        toml_harnesses = per_skill.get(name, {}).get("harnesses")
        if isinstance(toml_harnesses, list) and harness not in toml_harnesses:
            continue
        rel = f"skills/{name}/SKILL.md"
        content = skill_wrapper_body(name, harness, root_str,
                                     sync_command=sync_command)
        outputs.append((rel, content))

    return outputs


def _substrate_skills_dir(substrate: SubstrateConfig | None) -> Path | None:
    """Resolve <substrate>/skills/ from config.

    Returns None when substrate isn't loaded or [paths] skills is unset/absent.
    """
    if substrate is None or substrate.paths is None:
        return None
    skills = substrate.paths.skills
    if skills is None:
        return None
    return skills if skills.is_dir() else None


