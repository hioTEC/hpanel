# Single-line source statement that operators paste into ~/.bashrc / ~/.zshrc.
# Kept as a constant so write_path_sh, inject_shell_rc, and the post-configure
# hint print all use the same string (idempotency relies on byte-equal match).
PATH_SH_REL = ".config/dotpanel/path.sh"
PATH_SH_SOURCE_LINE = (
    "[ -f ~/.config/dotpanel/path.sh ] && source ~/.config/dotpanel/path.sh"
)
# Banner identifying dotpanel-generated path.sh. Whole-file ownership per ADR-3.
PATH_SH_BANNER = "# Generated by dotpanel; do not edit directly."


def _render_path_sh(bundled_bin: Path, substrate_bin: Path | None) -> str:
    """Render the whole-file body of ~/.config/dotpanel/path.sh.

    Bundled bin dir is always injected. Substrate bin dir injected only if
    supplied (resolved by caller from `[configure] substrate_bin`).
    """
    lines = [
        PATH_SH_BANNER,
        "# Source from your shell rc with:",
        f"#   {PATH_SH_SOURCE_LINE}",
        "#",
        "# Re-rendered by `dotpanel configure`. Absolute paths baked in at render time.",
        f'export PATH="{bundled_bin}:$PATH"',
    ]
    if substrate_bin is not None:
        lines.append(f'export PATH="{substrate_bin}:$PATH"')
    return "\n".join(lines) + "\n"


def write_path_sh(home: Path, dotpanel_root: Path, substrate_bin: Path | None,
                  *, dry_run: bool = False) -> tuple[str, Path]:
    """Write ~/.config/dotpanel/path.sh atomically.

    Returns (status, path) where status is one of "wrote", "noop", "would".
    Idempotent: rewrites only when content actually differs.
    """
    target = home / PATH_SH_REL
    bundled_bin = (dotpanel_root / "tools" / "bin").resolve()
    body = _render_path_sh(bundled_bin, substrate_bin)
    if target.exists():
        try:
            if target.read_text(encoding="utf-8") == body:
                return "noop", target
        except OSError:
            pass
    if dry_run:
        return "would", target
    target.parent.mkdir(parents=True, exist_ok=True)
    _write_atomic(target, body)
    return "wrote", target


def _detect_shell_rcs(home: Path) -> list[Path]:
    """Return the list of shell rc files to inject into.

    Detects bash + zsh on best-effort basis. Targets:
      - ~/.bashrc if it exists OR $SHELL ends in /bash
      - ~/.bash_profile if it exists (login shells like SSH read this, not .bashrc)
      - ~/.zshrc if it exists OR $SHELL ends in /zsh
      - ~/.zprofile if it exists (zsh login shells)
    If none exists, defaults to whatever $SHELL says, falling back to ~/.bashrc.
    """
    rcs: list[Path] = []
    shell = os.environ.get("SHELL", "")
    bashrc = home / ".bashrc"
    bash_profile = home / ".bash_profile"
    zshrc = home / ".zshrc"
    zprofile = home / ".zprofile"
    if bashrc.exists() or shell.endswith("/bash"):
        rcs.append(bashrc)
    if bash_profile.exists():
        rcs.append(bash_profile)
    if zshrc.exists() or shell.endswith("/zsh"):
        rcs.append(zshrc)
    if zprofile.exists():
        rcs.append(zprofile)
    if not rcs:
        rcs.append(bashrc)  # last resort: bash is the dominant default
    return rcs


def inject_shell_rc(home: Path, *, dry_run: bool = False) -> list[tuple[str, Path]]:
    """Append the path.sh source line to detected shell rc files.

    Idempotent: scans each rc for an existing line matching PATH_SH_SOURCE_LINE
    (byte-equal after strip) and skips if already present. Returns a list of
    (status, path) tuples where status is "appended", "noop", or "would".
    """
    results: list[tuple[str, Path]] = []
    target_line = PATH_SH_SOURCE_LINE.strip()
    for rc in _detect_shell_rcs(home):
        already = False
        if rc.exists():
            try:
                for line in rc.read_text(encoding="utf-8").splitlines():
                    if line.strip() == target_line:
                        already = True
                        break
            except OSError:
                already = False
        if already:
            results.append(("noop", rc))
            continue
        if dry_run:
            results.append(("would", rc))
            continue
        rc.parent.mkdir(parents=True, exist_ok=True)
        # Append (rather than rewrite) — minimal touch on operator-owned content.
        with rc.open("a", encoding="utf-8") as fh:
            # Pad with a leading newline so we never glue onto a prior non-newline.
            if rc.exists() and rc.stat().st_size > 0:
                # Ensure we start on a fresh line.
                # Re-reading is cheap; safer than assuming the file ended in \n.
                last = rc.read_text(encoding="utf-8")[-1:] if rc.stat().st_size else "\n"
                if last != "\n":
                    fh.write("\n")
            fh.write(f"# dotpanel: launcher PATH (idempotent)\n")
            fh.write(f"{PATH_SH_SOURCE_LINE}\n")
        results.append(("appended", rc))
    return results


def _resolve_substrate_bin(substrate: SubstrateConfig | None,
                           include_substrate_bin: bool | None) -> Path | None:
    """Decide whether (and which) substrate tools/bin dir to inject.

    Returns None when the substrate dir is unknown or explicitly disabled.
    `include_substrate_bin=True`  -> always include (FAIL if dir absent).
    `include_substrate_bin=False` -> never include.
    `include_substrate_bin=None`  -> auto: include iff resolved dir exists.
    """
    if include_substrate_bin is False:
        return None
    if substrate is None or substrate.configure is None:
        return None
    candidate = substrate.configure.substrate_bin
    if not candidate.is_dir():
        # In auto mode (None), missing dir means skip silently. In explicit
        # True mode the caller will surface this as a warning.
        return None
    return candidate.resolve()


def _try_find_substrate() -> SubstrateConfig | None:
    """Best-effort substrate discovery; never raises out of configure flow."""
    try:
        return find_substrate()
    except SubstrateNotFound:
        return None
    except Exception:
        return None


def _current_managed_skill_names(paths: DotpanelPaths) -> set[str]:
    """Compute the full set of skill names dotpanel currently manages (any harness).

    Union of:
      - USER_FACING_SKILLS (public skills from cli.py registry)
      - <substrate>/skills/*.md (D7 substrate-private skills)
    Minus any names listed in `.dotpanel.toml [skills] disabled`.

    This is the GLOBAL set — used for the managed-skills.json registry file.
    For prune decisions, use `_managed_skill_names_for_harness` instead, since
    a skill can declare `supported_harnesses: [claude]` and still belong in the
    registry while being an orphan on codex's side.
    """
    names: set[str] = set(USER_FACING_SKILLS)
    substrate = _try_find_substrate()
    if substrate is not None:
        substrate_skills_dir = _substrate_skills_dir(substrate)
        names |= set(_discover_substrate_skills(substrate_skills_dir))
        names -= set(substrate.skills.disabled)
    return names


def _managed_skill_names_for_harness(paths: DotpanelPaths, harness: str) -> set[str]:
    """Per-harness subset of managed skills — skills that SHOULD render into
    THIS harness's skill directory under current config.

    Honors substrate skill frontmatter `supported_harnesses`, public skill
    `.dotpanel.toml [skills.<name>] harnesses` overrides, and `[skills] disabled`.
    Mirrors the gating logic in `_gather_outputs` so prune sees the same view.
    """
    substrate = _try_find_substrate()
    disabled: set[str] = set()
    per_skill: dict[str, Any] = {}
    if substrate is not None:
        disabled = set(substrate.skills.disabled)
        per_skill = dict(substrate.skills.per_skill)

    substrate_skills_dir = _substrate_skills_dir(substrate) if substrate else None
    substrate_skills = _discover_substrate_skills(substrate_skills_dir) if substrate_skills_dir else {}

    names: set[str] = set()
    # Substrate skills with this harness supported
    for name, skill in substrate_skills.items():
        if name in disabled:
            continue
        if harness not in skill.supported_harnesses:
            continue
        toml_harnesses = per_skill.get(name, {}).get("harnesses")
        if isinstance(toml_harnesses, list) and harness not in toml_harnesses:
            continue
        names.add(name)

    # Public skills not claimed by substrate (substrate overrides public on collision)
    for name in USER_FACING_SKILLS:
        if name in substrate_skills:
            continue
        if name in disabled:
            continue
        toml_harnesses = per_skill.get(name, {}).get("harnesses")
        if isinstance(toml_harnesses, list) and harness not in toml_harnesses:
            continue
        names.add(name)

    return names


def _managed_skills_registry_path(home: Path) -> Path:
    """Path to ~/.dotpanel/managed-skills.json (C12 registry)."""
    return home / ".dotpanel" / "managed-skills.json"


def _actual_skills_dir(paths: DotpanelPaths, harness: str) -> Path | None:
    """Harness-native skills directory for generated user-facing wrappers."""
    return paths.skills_root(harness, None)


def _write_managed_skills_registry(home: Path, names: list[str], harnesses: list[str],
                                   *, dry_run: bool) -> None:
    """Atomically write the managed-skills registry.

    Schema:
        {
          "schema_version": "1",
          "skills": ["plan", "review", "ship", "sync", "tool", "wrap"],
          "harnesses": ["claude", "codex", "kimi"],
          "written_at": "<iso-utc>"
        }
    """
    if dry_run:
        return
    payload = {
        "schema_version": "1",
        "skills": sorted(set(names)),
        "harnesses": sorted(set(harnesses)),
    }
    import datetime as _dt
    payload["written_at"] = _dt.datetime.now(_dt.timezone.utc).strftime(
        "%Y-%m-%dT%H:%M:%SZ"
    )
    target = _managed_skills_registry_path(home)
    target.parent.mkdir(parents=True, exist_ok=True)
    _write_atomic(target, json.dumps(payload, indent=2, sort_keys=True) + "\n")


def _prune_orphan_skills(paths: DotpanelPaths,
                        harnesses: list[str], *, dry_run: bool,
                        result: "ConfigureResult") -> None:
    """Remove ~/.<harness>/skills/<orphan>/ for skills not valid in that harness.

    Uses per-harness `_managed_skill_names_for_harness` so that a skill declaring
    `supported_harnesses: [claude]` correctly looks like an orphan from codex's
    perspective even though it remains in the global managed-skills registry.

    Each orphan dir must contain a banner-marked SKILL.md (so we don't delete
    user-created skill directories). Empty parent skill/ dirs after removal
    are left in place.
    """
    for harness in harnesses:
        if harness == "kimi":
            # kimi has no native skills surface in this setup; nothing to prune.
            continue
        try:
            home = paths.output_root(harness, None)
        except ValueError:
            continue
        skills_dir = _actual_skills_dir(paths, harness)
        if skills_dir is None:
            continue
        if not skills_dir.is_dir():
            continue
        valid_for_harness = _managed_skill_names_for_harness(paths, harness)
        for child in sorted(skills_dir.iterdir()):
            if not child.is_dir():
                continue
            if child.name in valid_for_harness:
                continue
            skill_md = child / "SKILL.md"
            if not skill_md.is_file():
                continue
            # Only prune banner-marked skills (dotpanel-managed).
            if not has_dotpanel_banner(skill_md):
                result.conflicts.append(
                    f"orphan skill at {child} lacks dotpanel banner; "
                    "leaving in place"
                )
                continue
            action = f"PRUNE-SKILL {child}"
            if not dry_run:
                try:
                    # Remove the SKILL.md (and any other banner files) plus the
                    # directory itself if empty.
                    for f in child.rglob("*"):
                        if f.is_file():
                            f.unlink()
                    for d in sorted(child.rglob("*"), key=lambda p: -len(str(p))):
                        if d.is_dir() and not any(d.iterdir()):
                            d.rmdir()
                    if not any(child.iterdir()):
                        child.rmdir()
                except OSError as exc:
                    result.conflicts.append(f"prune {child} failed: {exc}")
                    continue
            result.actions.append(action)


def cmd_configure(paths: DotpanelPaths, harness: str, check: bool, force: bool,
                  dry_run: bool, output_dir: Path | None,
                  *, include_substrate_bin: bool | None = None,
                  inject_shell_rc_flag: bool = False,
                  prune_orphan_skills: bool = False) -> int:
    """Render harness adapters from templates."""
    # Validate prerequisites. Skip the stale-rename invariant here — configure
    # is exactly the thing that re-renders harness output to clear it, so
    # gating configure on it would create a chicken-and-egg cycle during
    # cutover (operator can't run configure to fix the stale-rename FAILs
    # because configure's doctor preflight refuses).
    doctor_rc = cmd_doctor(paths, skip_stale_rename=True)
    if doctor_rc != 0:
        print("FAIL  dotpanel doctor preconditions not met; resolve before configure.", file=sys.stderr)
        return doctor_rc

    targets = ("claude", "codex", "kimi") if harness == "all" else (harness,)
    overall_result = ConfigureResult()

    # `--check` runs the same planner as the real configure, but with dry_run=True
    # so no files are written. This catches placeholder bugs AND conflict-handling
    # failures (non-banner files at managed paths, foreign symlinks, etc.) per ADR-3.
    plan_dry_run = dry_run or check

    for target in targets:
        out_root = paths.output_root(target, output_dir)
        outputs = _gather_outputs(paths, target)
        if not outputs:
            print(f"WARN  no templates for harness {target}", file=sys.stderr)
            continue
        for rel, content in outputs:
            # Validate placeholder rendering on every output (catches template bugs)
            if "{{" in content or "}}" in content:
                overall_result.conflicts.append(f"{target}/{rel}: unrendered placeholder in output")
            # Run the conflict planner (also in --check mode, just without writes)
            _configure_one_file(rel, content, out_root, target, force, plan_dry_run, paths.home, overall_result)

    if check:
        if overall_result.conflicts:
            for c in overall_result.conflicts:
                print(f"CHECK-FAIL  {c}", file=sys.stderr)
            return 2
        print(f"OK  configure --check passed (targets: {','.join(targets)})")
        return 0

    if overall_result.conflicts:
        for c in overall_result.conflicts:
            print(f"CONFLICT  {c}", file=sys.stderr)
        return 2

    # Mark successful configure for ADR-3 audit cutover-state detection
    if not dry_run and overall_result.actions:
        try:
            dotpanel_state_dir = paths.home / ".dotpanel"
            dotpanel_state_dir.mkdir(parents=True, exist_ok=True)
            _write_atomic(dotpanel_state_dir / "last-configure-success",
                          f"{','.join(targets)}\n")
        except OSError:
            pass

    # C12: write managed-skills registry (after successful planning, before
    # prune so prune sees the up-to-date current_names set).
    current_names = _current_managed_skill_names(paths)
    if not dry_run:
        try:
            _write_managed_skills_registry(
                paths.home, list(current_names), list(targets), dry_run=dry_run,
            )
        except OSError as exc:
            print(f"WARN  could not write managed-skills registry: {exc}",
                  file=sys.stderr)

    # C12: orphan prune (off by default; opt-in via --prune-orphan-skills).
    if prune_orphan_skills:
        _prune_orphan_skills(paths, list(targets),
                             dry_run=dry_run, result=overall_result)

    for action in overall_result.actions:
        print(f"{'WOULD' if dry_run else 'OK'}  {action}")
    if not overall_result.actions:
        print("OK  configuration already current")

    # D5: PATH injection. Write ~/.config/dotpanel/path.sh and optionally
    # append the source line to ~/.bashrc / ~/.zshrc. Both writes are
    # idempotent. Path injection is skipped in --output-dir mode (sandbox)
    # because the operator's $HOME isn't the rendering target.
    if output_dir is None:
        substrate = _try_find_substrate()
        substrate_bin = _resolve_substrate_bin(substrate, include_substrate_bin)
        try:
            status, target = write_path_sh(paths.home, paths.root, substrate_bin,
                                           dry_run=dry_run)
        except OSError as exc:
            print(f"WARN  could not write {paths.home / PATH_SH_REL}: {exc}",
                  file=sys.stderr)
        else:
            tag = {"wrote": "OK", "noop": "OK", "would": "WOULD"}[status]
            verb = {"wrote": "wrote", "noop": "current",
                    "would": "would-write"}[status]
            print(f"{tag}  {verb} {target}")
            if status == "wrote":
                print(
                    f"Add this line to ~/.bashrc / ~/.zshrc to activate launchers:\n"
                    f"    {PATH_SH_SOURCE_LINE}"
                )
        if inject_shell_rc_flag:
            try:
                rc_results = inject_shell_rc(paths.home, dry_run=dry_run)
            except OSError as exc:
                print(f"WARN  could not inject shell rc: {exc}", file=sys.stderr)
            else:
                for rc_status, rc_path in rc_results:
                    rc_tag = {"appended": "OK", "noop": "OK",
                              "would": "WOULD"}[rc_status]
                    rc_verb = {"appended": "appended source line to",
                               "noop": "source line already present in",
                               "would": "would-append source line to"}[rc_status]
                    print(f"{rc_tag}  {rc_verb} {rc_path}")
    return 0


