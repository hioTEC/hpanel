def cmd_audit(paths: DotpanelPaths) -> int:
    """Structural invariants for CI/pre-commit. Per ADR-3 Audit Surface."""
    issues: list[str] = []

    # 1. Persona symlink target exists and is dir
    persona_link = paths.root / "persona"
    if persona_link.exists():
        if not persona_link.is_symlink():
            issues.append(f"persona at {persona_link} should be a symlink")
        else:
            target = persona_link.resolve()
            if not target.is_dir():
                issues.append(f"persona symlink target {target} is not a directory")

    # 2. Required persona files exist at flat root
    if persona_link.exists():
        if not (persona_link / "voice.md").exists():
            issues.append("persona/voice.md missing")
        if not (persona_link / "identity.yaml").exists():
            issues.append("persona/identity.yaml missing")

    # 3. DOTPANEL_MANAGED_JSON list visibility
    print(f"INFO  DOTPANEL_MANAGED_JSON: {DOTPANEL_MANAGED_JSON}")

    # 4. Generated files in harness homes carry banner. Before the first
    # successful configure (no ~/.dotpanel/last-configure-success marker),
    # missing banners are INFO; afterwards they are FAIL (regression check).
    last_configure = paths.home / ".dotpanel" / "last-configure-success"
    cutover_done = last_configure.exists()
    for harness, home_dir, excluded in (
        ("claude", paths.claude_home, CLAUDE_EXCLUDED),
        ("codex", paths.codex_home, CODEX_EXCLUDED),
        ("kimi", paths.kimi_home, KIMI_EXCLUDED),
    ):
        if not home_dir.exists():
            continue
        candidate_paths = []
        for known in ("CLAUDE.md", "AGENTS.md", "settings.json", "config.toml"):
            p = home_dir / known
            if p.exists():
                candidate_paths.append(p)
        skills_dir = _actual_skills_dir(paths, harness)
        if skills_dir is not None and skills_dir.is_dir():
            for skill_md in skills_dir.glob("*/SKILL.md"):
                candidate_paths.append(skill_md)
        for p in candidate_paths:
            try:
                rel = str(p.relative_to(home_dir))
            except ValueError:
                rel = str(p.relative_to(paths.home))
            if _excluded_path(rel, harness):
                continue
            if _is_json(p.name):
                if not is_managed_json(p, paths.home):
                    continue
                continue
            if not has_dotpanel_banner(p):
                msg = f"{p}: no dotpanel banner"
                if cutover_done:
                    issues.append(msg)
                else:
                    print(f"INFO  {msg} (pre-configure file)")

    # 5. Persona excluded from dist artifacts — full inspection delegated to
    # `dotpanel audit --dist`; the default audit only flags presence.
    dist = paths.root / "dist"
    if dist.exists() and any(dist.iterdir()):
        print(
            "INFO  Build artifacts present in dist/. "
            "Run `dotpanel audit --dist` for full member inspection."
        )

    if issues:
        for issue in issues:
            print(f"FAIL  {issue}")
        return 2
    print("OK  dotpanel audit passed")
    return 0


def _archive_members(archive: Path) -> Iterable[str]:
    """Yield member names (POSIX-style paths) from a wheel or sdist archive.

    Wheels are zip; sdists are gzipped tar. Other extensions are skipped by the
    caller. Raises on unreadable archives so audit exits non-zero loudly.
    """
    name = archive.name
    if name.endswith(".whl") or name.endswith(".zip"):
        with zipfile.ZipFile(archive) as zf:
            for member in zf.namelist():
                yield member
    elif name.endswith(".tar.gz") or name.endswith(".tgz"):
        with tarfile.open(archive, mode="r:gz") as tf:
            for member in tf.getnames():
                yield member


def cmd_audit_dist(paths: DotpanelPaths) -> int:
    """Inspect built dist artifacts; FAIL if any persona content leaked.

    Per ADR-2: dotpanel/persona is a gitignored symlink and MANIFEST.in carries
    `prune persona`, but build tooling can still misbehave (follow symlinks,
    miss MANIFEST entries, package-data globs). This subcommand opens each
    archive in dist/ and rejects members whose path begins with `persona/` or
    contains `/persona/`.
    """
    dist = paths.root / "dist"
    if not dist.exists():
        print("INFO  no dist/ directory — nothing to inspect")
        return 0

    archives = sorted(
        p for p in dist.iterdir()
        if p.is_file() and (
            p.name.endswith(".whl")
            or p.name.endswith(".tar.gz")
            or p.name.endswith(".tgz")
            or p.name.endswith(".zip")
        )
    )
    if not archives:
        print("INFO  dist/ contains no recognized build artifacts (.whl/.tar.gz)")
        return 0

    issues: list[str] = []
    for archive in archives:
        try:
            members = list(_archive_members(archive))
        except (zipfile.BadZipFile, tarfile.TarError, OSError) as exc:
            issues.append(f"{archive.name}: failed to read archive ({exc})")
            continue
        for member in members:
            # Normalize: remove any leading wheel-internal prefix (e.g. "dotpanel-0.3.0/")
            # so we can match the logical path.
            parts = member.split("/")
            if "persona" in parts:
                issues.append(f"{archive.name}: persona content at member {member!r}")

    if issues:
        for issue in issues:
            print(f"FAIL  {issue}", file=sys.stderr)
        return 2
    print(f"OK  no persona content in {len(archives)} archive(s)")
    return 0


