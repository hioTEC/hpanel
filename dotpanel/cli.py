def _write_init_file_if_missing(path: Path, body: str, *, executable: bool = False,
                                results: list[str] | None = None) -> None:
    """Write `body` to `path` only if the file doesn't exist yet.

    Idempotent: `dotpanel init` can be re-run on an existing substrate
    without clobbering operator content. Returns nothing; appends a status
    string to `results` if provided.
    """
    if path.exists():
        if results is not None:
            results.append(f"OK  skill skeleton already exists: {path}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body)
    if executable:
        path.chmod(0o755)
    if results is not None:
        results.append(f"WROTE  {path}")


