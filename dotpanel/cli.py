def dotpanel_root() -> Path:
    """Absolute path to dotpanel repository root.

    With `dotpanel/dotpanel/cli.py`, `parents[1]` returns the repo root in
    editable installs. Wheel installs must include protocol/, harness/, tools/
    as package data (verified by `dotpanel doctor`).
    """
    return Path(__file__).resolve().parents[1]


def persona_dir(root: Path | None = None) -> Path:
    """Path to the (flat) persona directory.

    Per the post-slug architecture, persona is a single directory under
    `<dotpanel-root>/persona/` (a gitignored symlink to the operator's private
    persona repo). There is no `<slug>/` indirection.
    """
    root = root or dotpanel_root()
    return root / "persona"


