@dataclass(frozen=True)
class DotpanelPaths:
    root: Path
    home: Path

    @classmethod
    def default(cls) -> "DotpanelPaths":
        return cls(root=dotpanel_root(), home=Path(os.environ.get("HOME", "~")).expanduser())

    @property
    def protocol(self) -> Path:
        return self.root / "protocol"

    @property
    def harness(self) -> Path:
        return self.root / "harness"

    @property
    def claude_templates(self) -> Path:
        return self.harness / "claude" / "templates"

    @property
    def codex_templates(self) -> Path:
        return self.harness / "codex" / "templates"

    @property
    def kimi_templates(self) -> Path:
        return self.harness / "kimi" / "templates"

    @property
    def claude_home(self) -> Path:
        return self.home / ".claude"

    @property
    def codex_home(self) -> Path:
        return self.home / ".codex"

    @property
    def agents_home(self) -> Path:
        return self.home / ".agents"

    @property
    def kimi_home(self) -> Path:
        return self.home / ".kimi"

    def output_root(self, harness: str, override: Path | None = None) -> Path:
        if override:
            return override / harness
        if harness == "claude":
            return self.claude_home
        if harness == "codex":
            return self.codex_home
        if harness == "kimi":
            return self.kimi_home
        raise ValueError(f"unknown harness: {harness}")

    def skills_root(self, harness: str, override: Path | None = None) -> Path | None:
        if harness == "claude":
            return self.output_root("claude", override) / "skills"
        if harness == "codex":
            if override:
                return override / "agents" / "skills"
            return self.agents_home / "skills"
        if harness == "kimi":
            return None
        raise ValueError(f"unknown harness: {harness}")


