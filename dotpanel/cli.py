def cmd_uninstall(paths: DotpanelPaths, harness: str, include_settings: bool,
                  dry_run: bool, *, launchers: bool = False) -> int:
    targets = ("claude", "codex", "kimi") if harness == "all" else (harness,)
    actions: list[str] = []
    for target in targets:
        home = paths.output_root(target, None)
        # Find banner-marked files to remove
        search_roots = [home] if home.exists() else []
        skills_root = _actual_skills_dir(paths, target)
        if skills_root is not None and skills_root.exists() and skills_root not in search_roots:
            search_roots.append(skills_root)
        for root in search_roots:
            for fp in root.rglob("*"):
                if not fp.is_file():
                    continue
                try:
                    rel = str(fp.relative_to(home))
                except ValueError:
                    rel = str(fp.relative_to(paths.home))
                if _excluded_path(rel, target):
                    continue
                if _is_json(fp.name):
                    if include_settings and is_managed_json(fp, paths.home):
                        actions.append(f"REMOVE-JSON {fp}")
                        if not dry_run:
                            fp.unlink()
                    continue
                if has_dotpanel_banner(fp):
                    actions.append(f"REMOVE {fp}")
                    if not dry_run:
                        fp.unlink()
        # Remove empty skill subdirs
        skills = _actual_skills_dir(paths, target)
        if skills is not None and skills.is_dir():
            for d in sorted(skills.glob("*"), reverse=True):
                if d.is_dir() and not any(d.iterdir()):
                    actions.append(f"RMDIR {d}")
                    if not dry_run:
                        d.rmdir()

    # D5: optional --launchers removes ~/.config/dotpanel/path.sh.
    if launchers:
        path_sh = paths.home / PATH_SH_REL
        if path_sh.exists():
            actions.append(f"REMOVE-LAUNCHERS {path_sh}")
            if not dry_run:
                try:
                    path_sh.unlink()
                except OSError as exc:
                    print(f"WARN  could not remove {path_sh}: {exc}", file=sys.stderr)

    for a in actions:
        print(f"{'WOULD' if dry_run else 'OK'}  {a}")
    if not actions:
        print("OK  no banner-marked files found")
    return 0


