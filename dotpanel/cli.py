# Subcommand: doctor
# ---------------------------------------------------------------------------

def cmd_doctor(paths: DotpanelPaths,
               *, skip_stale_rename: bool = False) -> int:
    """Verify install, symlink, persona, templates, paths.

    Implements the consolidated 15-row invariants table (IC-SG-4). FAIL items
    accumulate; WARN items print to stderr but don't change exit code unless
    a FAIL was also recorded.

    `skip_stale_rename` is accepted for back-compat with internal callers
    that pre-date the removal of the stale-rename detector; it has no effect.
    """
    issues: list[str] = []
    warnings: list[str] = []

    # Required directories under dotpanel root
    for required in (paths.protocol, paths.protocol / "skills", paths.protocol / "rules",
                     paths.protocol / "workspace.md", paths.harness, paths.claude_templates,
                     paths.codex_templates, paths.kimi_templates):
        if not required.exists():
            issues.append(f"MISSING required path: {required}")

    # pyproject.toml at root (editable-install relocation guard)
    pyproject = paths.root / "pyproject.toml"
    if not pyproject.exists():
        issues.append(
            f"pyproject.toml missing at {pyproject}. "
            "Repo may have been moved without re-running 'pip install -e .'"
        )

    # Editable install pointing at this source location
    try:
        spec = importlib.util.find_spec("dotpanel")
        if spec and spec.origin:
            installed = Path(spec.origin).resolve().parents[0]
            source = paths.root / "dotpanel"
            if installed.resolve() != source.resolve():
                issues.append(
                    f"dotpanel installed at {installed} but source at {source}. "
                    f"Re-run 'pip install -e .' from {paths.root}"
                )
    except Exception as exc:
        issues.append(f"editable-install detection failed: {exc}")

    # Persona symlink
    persona_link = paths.root / "persona"
    if not persona_link.exists():
        issues.append(
            f"persona symlink missing at {persona_link}. "
            "Run `dotpanel init [--persona-root <path>]` to create."
        )
    else:
        if not persona_link.is_symlink():
            issues.append(f"persona at {persona_link} is not a symlink (expected symlink)")
        else:
            target = persona_link.resolve()
            if not target.is_dir():
                issues.append(f"persona symlink target {target} is not a directory")

        # Required persona files exist at flat root
        if not (persona_link / "voice.md").exists():
            issues.append(f"persona/voice.md missing at {persona_link / 'voice.md'}")
        if not (persona_link / "identity.yaml").exists():
            issues.append(f"persona/identity.yaml missing at {persona_link / 'identity.yaml'}")

    # Templates exist
    for template in (paths.claude_templates / "CLAUDE.md", paths.claude_templates / "settings.json",
                     paths.codex_templates / "AGENTS.md", paths.codex_templates / "config.toml",
                     paths.kimi_templates / "AGENTS.md"):
        if not template.exists():
            issues.append(f"MISSING template: {template}")

    # Invariant 7 + 8: .dotpanel.toml schema validation + path traversal (H9).
    # Both are surfaced via the config loader; loader raises SchemaError on
    # path-traversal or other invariant violations. We just call find_substrate
    # and treat SchemaError as FAIL. SubstrateNotFound is NOT a failure —
    # operators may run dotpanel from a tmp dir without a substrate.
    try:
        find_substrate()
    except SubstrateNotFound:
        pass  # legal — no substrate discoverable
    except Exception as exc:
        # SchemaError (path-traversal, type errors, etc.) or unexpected
        # exceptions from TOML parsing -> FAIL.
        issues.append(f".dotpanel.toml schema validation: {exc}")

    # Invariant 11: age + age-keygen binaries on PATH (H6). FAIL because
    # secrets verbs are unusable without them.
    for binary in ("age", "age-keygen"):
        if shutil.which(binary) is None:
            issues.append(
                f"`{binary}` binary not on PATH. Install:\n"
                f"      macOS:    brew install age\n"
                f"      Debian:   apt install age\n"
                f"      Other:    https://github.com/FiloSottile/age/releases"
            )

    # Invariant 10: launcher PATH resolution (WARN). `claw` and `codx` must
    # resolve under <dotpanel-root>/tools/bin/ — otherwise another binary on
    # PATH is shadowing the dotpanel launcher. (Substrate-side shims in
    # the configured substrate_bin dir also count as valid.)
    bundled_bin = (paths.root / "tools" / "bin").resolve()
    for launcher in ("claw", "codx"):
        resolved = shutil.which(launcher)
        if resolved is None:
            warnings.append(
                f"`{launcher}` not on PATH. Open a new shell, or "
                f"`source ~/.config/dotpanel/path.sh` in this one."
            )
            continue
        resolved_path = Path(resolved).resolve()
        # Allow shim paths (substrate's tools/bin may host shims that exec
        # the bundled launcher) — only warn when resolved path is in neither
        # the bundled dir nor the configured substrate bin.
        substrate_bin = _try_find_substrate()
        substrate_bin_path: Path | None = None
        if substrate_bin is not None and substrate_bin.configure is not None:
            substrate_bin_path = substrate_bin.configure.substrate_bin.resolve()
        ok = (resolved_path.parent == bundled_bin
              or (substrate_bin_path is not None
                  and resolved_path.parent == substrate_bin_path))
        if not ok:
            warnings.append(
                f"`{launcher}` resolves to {resolved_path} (expected "
                f"{bundled_bin}/{launcher}). Another binary named `{launcher}` "
                f"on PATH is shadowing the dotpanel launcher."
            )

    # Invariant 9: backend vs llm_scope coherence (WARN). Every
    # [backends.*].variants.*.key should match at least one [secrets]
    # llm_scope fnmatch pattern. Mismatched keys mean the variant works for
    # the launcher but vscode-server (which inherits via `secrets export
    # --scope llm`) does NOT have the key.
    sub = _try_find_substrate()
    if sub is not None:
        import fnmatch as _fnmatch
        llm_patterns = list(sub.secrets.llm_scope)
        if llm_patterns:
            for provider_name, provider in sub.backends.providers.items():
                for variant_name, variant in provider.variants.items():
                    key = variant.key
                    if not key:
                        continue
                    if not any(_fnmatch.fnmatchcase(key, p) for p in llm_patterns):
                        warnings.append(
                            f"backends.{provider_name}.variants.{variant_name}.key "
                            f"= {key!r} does not match any [secrets] "
                            f"llm_scope pattern. `{provider_name} --{variant_name}` "
                            "will work, but vscode-server (which inherits via "
                            "`secrets export --scope llm`) will NOT have this key."
                        )

    # Invariant 16: VSCode Codex extension needs server-env-setup so the
    # extension host inherits env_key-based LLM credentials.
    for vscode_home_name in (".vscode-server", ".vscode-server-insiders"):
        vscode_home = paths.home / vscode_home_name
        extensions_dir = vscode_home / "extensions"
        if not extensions_dir.is_dir():
            continue
        has_codex_extension = any(
            child.is_dir() and child.name.startswith("openai.chatgpt-")
            for child in extensions_dir.iterdir()
        )
        if has_codex_extension and not (vscode_home / "server-env-setup").is_file():
            warnings.append(
                f"{vscode_home}/server-env-setup missing. VSCode Codex extension "
                "may not inherit LLM env keys; install a setup file that runs "
                "`dotpanel secrets export --scope llm` before vscode-server starts."
            )

    # Invariant 12: multi-checkout detection (WARN). `pip show dotpanel`
    # should show exactly one editable install. This is best-effort: the
    # active editable install plus an in-repo legacy `dotpanel.egg-info/`
    # directory both register as distributions; only WARN when two different
    # SOURCE locations are detected (not when egg-info shadows the same source).
    try:
        import importlib.metadata as _md
        dists = list(_md.distributions())
        dotpanel_dists = [d for d in dists if d.metadata["Name"] == "dotpanel"]
        if len(dotpanel_dists) > 1:
            # Resolve each distribution to its actual source dir (where
            # dotpanel/cli.py lives). For dev-mode egg-info in the source
            # repo, that's the repo root. For a real editable install,
            # we read the .pth file or follow PackagePath relpaths.
            source_dirs: set[str] = set()
            for d in dotpanel_dists:
                # Walk to dotpanel/__init__.py and take its parent.
                for fp in (d.files or []):
                    if str(fp).endswith("dotpanel/__init__.py"):
                        try:
                            abs_path = Path(str(d.locate_file(fp))).resolve()
                            source_dirs.add(str(abs_path.parents[1]))
                        except (OSError, ValueError):
                            pass
                        break
            if len(source_dirs) > 1:
                warnings.append(
                    f"multiple `dotpanel` source checkouts detected:\n        "
                    + "\n        ".join(sorted(source_dirs))
                    + "\n      Run `pip uninstall dotpanel` until only one "
                    "editable install remains; then `pip install -e .` from "
                    "the canonical source dir."
                )
    except Exception:
        # Best-effort; metadata can fail in odd environments.
        pass

    # Invariant 13: stuck sync-state check (per design doc C6 doctor invariant).
    try:
        from .sync import _load_state, STUCK_AGE_SECONDS
        state = _load_state(paths.home)
        if state.is_active() and state.age_seconds() > STUCK_AGE_SECONDS:
            issues.append(
                f"stuck sync state at phase {state.phase!r} "
                f"(age {int(state.age_seconds())}s); run 'dotpanel sync resume' "
                "or 'dotpanel sync pull --force-restart'"
            )
    except Exception as exc:
        # Don't fail doctor if state loader is broken — just surface the warning.
        print(f"WARN  sync state check failed: {exc}", file=sys.stderr)

    # Report
    for warn in warnings:
        print(f"WARN  {warn}", file=sys.stderr)
    if issues:
        for issue in issues:
            print(f"FAIL  {issue}")
        return 2
    print(f"OK  dotpanel doctor passed (root: {paths.root})")
    return 0


