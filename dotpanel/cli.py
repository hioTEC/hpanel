def has_dotpanel_banner(path: Path) -> bool:
    """Banner detection: scans first BANNER_SCAN_LINES lines.

    Accommodates YAML frontmatter (which appears before the banner in skill wrappers).
    """
    if not path.is_file():
        return False
    try:
        with path.open(encoding="utf-8", errors="replace") as fh:
            for _ in range(BANNER_SCAN_LINES):
                line = fh.readline()
                if not line:
                    return False
                if "Generated by dotpanel" in line:
                    return True
    except OSError:
        return False
    return False


def is_managed_json(path: Path, home: Path) -> bool:
    abs_path = str(path.resolve())
    for entry in DOTPANEL_MANAGED_JSON:
        managed = Path(entry.replace("~", str(home))).resolve()
        if Path(abs_path) == managed:
            return True
    return False


