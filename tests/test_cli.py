class ConstantsTests(unittest.TestCase):
    def test_version_is_semver(self) -> None:
        self.assertRegex(__version__, r"^\d+\.\d+\.\d+(?:[-+\w.]*)?$")

    def test_user_facing_skills_have_canonical_files(self) -> None:
        from dotpanel.cli import CANONICAL_SKILL_FILES, SKILL_TITLES, SKILL_DESCRIPTIONS
        for skill in USER_FACING_SKILLS:
            self.assertIn(skill, CANONICAL_SKILL_FILES)
            self.assertIn(skill, SKILL_TITLES)
            self.assertIn(skill, SKILL_DESCRIPTIONS)

    def test_managed_json_list_is_short(self) -> None:
        # Per ADR-3 "doctor warns if list exceeds 5 entries" trigger threshold
        self.assertLessEqual(len(DOTPANEL_MANAGED_JSON), 5)

    def test_d7_curriculum_bridge_relocated_to_substrate(self) -> None:
        # D7: curriculum-bridge moved to substrate skills/ — public set drops it.
        self.assertNotIn("curriculum-bridge", USER_FACING_SKILLS)

    def test_d7_teamleader_relocated_to_substrate(self) -> None:
        # D7: teamleader moved to substrate skills/ — public set drops it.
        self.assertNotIn("teamleader", USER_FACING_SKILLS)

    def test_c12_slash_sync_replaces_slash_dot(self) -> None:
        # C12: /dot renamed to /sync.
        self.assertIn("sync", USER_FACING_SKILLS)
        self.assertNotIn("dot", USER_FACING_SKILLS)

    def test_c12_sync_canonical_filename_unchanged(self) -> None:
        # C12: skill renames to "sync" but canonical body remains config-sync.md.
        from dotpanel.cli import CANONICAL_SKILL_FILES
        self.assertEqual(CANONICAL_SKILL_FILES["sync"], "config-sync.md")


class RenderTextTests(unittest.TestCase):
    def test_renders_dotpanel_root(self) -> None:
        out = render_text("see {{DOTPANEL_ROOT}}/persona/voice.md", "/foo")
        self.assertEqual(out, "see /foo/persona/voice.md")

    def test_renders_sync_command_placeholder(self) -> None:
        out = render_text("Run {{SYNC_COMMAND}} push", "/foo")
        self.assertEqual(out, "Run dotpanel sync push")

    def test_renders_sync_command_custom_override(self) -> None:
        out = render_text("Run {{SYNC_COMMAND}}", "/foo", sync_command="my-sync run")
        self.assertEqual(out, "Run my-sync run")

    def test_no_placeholders_passes_through(self) -> None:
        self.assertEqual(render_text("plain text", "/foo"), "plain text")


class BannerTests(unittest.TestCase):
    def test_first_line_banner_detected(self) -> None:
        with TemporaryDirectory() as t:
            f = Path(t) / "x.md"
            f.write_text("Generated by dotpanel test\nbody\n")
            self.assertTrue(has_dotpanel_banner(f))

    def test_banner_after_yaml_frontmatter_detected(self) -> None:
        # Critical case from round-3 N1: SKILL.md wrappers have YAML frontmatter
        # ABOVE the banner. has_dotpanel_banner must scan first 10 lines.
        with TemporaryDirectory() as t:
            f = Path(t) / "x.md"
            f.write_text("---\nname: foo\ndescription: bar\n---\n\nGenerated by dotpanel\nbody\n")
            self.assertTrue(has_dotpanel_banner(f))

    def test_banner_beyond_scan_window_not_detected(self) -> None:
        with TemporaryDirectory() as t:
            f = Path(t) / "x.md"
            # 12 lines of frontmatter then banner — beyond default BANNER_SCAN_LINES=10
            lines = ["lorem ipsum"] * 12 + ["Generated by dotpanel"]
            f.write_text("\n".join(lines))
            self.assertFalse(has_dotpanel_banner(f))


