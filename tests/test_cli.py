def _seed_dotpanel_tree(root: Path, persona_root: Path | None = None) -> None:
    """Create minimum file tree for cmd_doctor/cmd_configure to work in a tmp root."""
    (root / "protocol" / "skills").mkdir(parents=True)
    (root / "protocol" / "rules").mkdir(parents=True)
    (root / "protocol" / "reference").mkdir(parents=True)
    (root / "protocol" / "workspace.md").write_text("# Universal protocol\n")

    (root / "harness" / "claude" / "templates").mkdir(parents=True)
    (root / "harness" / "claude" / "templates" / "CLAUDE.md").write_text(
        "<!-- Generated by dotpanel; do not edit directly. -->\nRead {{DOTPANEL_ROOT}}/persona/voice.md\nthen {{DOTPANEL_ROOT}}/protocol/workspace.md\n"
    )
    (root / "harness" / "claude" / "templates" / "settings.json").write_text(
        '{"language": "english"}\n'
    )
    (root / "harness" / "codex" / "templates").mkdir(parents=True)
    (root / "harness" / "codex" / "templates" / "AGENTS.md").write_text(
        "<!-- Generated by dotpanel; do not edit directly. -->\nRead {{DOTPANEL_ROOT}}/persona/voice.md\nthen {{DOTPANEL_ROOT}}/protocol/workspace.md\n"
    )
    (root / "harness" / "codex" / "templates" / "config.toml").write_text(
        "# Generated by dotpanel; do not edit directly.\nmodel = \"placeholder\"\n"
    )
    (root / "harness" / "kimi" / "templates").mkdir(parents=True)
    (root / "harness" / "kimi" / "templates" / "AGENTS.md").write_text(
        "<!-- Generated by dotpanel; do not edit directly. -->\nRead {{DOTPANEL_ROOT}}/persona/voice.md\nthen {{DOTPANEL_ROOT}}/protocol/workspace.md\n"
    )

    (root / "pyproject.toml").write_text("# placeholder for doctor\n")

    # Set up canonical skill files (referenced by skill_wrapper_body / configure)
    for filename in ("plan-discussion.md", "code-review.md", "ship-pipeline.md",
                     "session-wrap.md", "config-sync.md",
                     "tool-lifecycle.md", "curriculum-bridge.md", "design-audit.md"):
        (root / "protocol" / "skills" / filename).write_text(f"# {filename}\n")

    # Persona symlink (simulating dotpanel init result) — flat persona, no slug
    if persona_root:
        persona_root.mkdir(parents=True, exist_ok=True)
        (persona_root / "voice.md").write_text("# voice\n")
        (persona_root / "identity.yaml").write_text(
            "name:\n  chinese: \"testop\"\nhandle: testop\nemail: test@example.com\n"
        )
        (root / "persona").symlink_to(persona_root)


