class AuditDistTests(unittest.TestCase):
    def test_no_dist_dir_passes(self) -> None:
        with TemporaryDirectory() as t:
            paths = DotpanelPaths(root=Path(t), home=Path(t))
            with redirect_stdout(StringIO()):
                self.assertEqual(cmd_audit_dist(paths), 0)

    def test_dist_with_persona_member_in_whl_fails(self) -> None:
        with TemporaryDirectory() as t:
            root = Path(t)
            (root / "dist").mkdir()
            whl = root / "dist" / "dotpanel-x-py3-none-any.whl"
            with zipfile.ZipFile(whl, "w") as zf:
                zf.writestr("dotpanel/__init__.py", "x = 1\n")
                zf.writestr("persona/leak.md", "leaked!")
            paths = DotpanelPaths(root=root, home=root)
            with redirect_stdout(StringIO()), redirect_stderr(StringIO()):
                self.assertEqual(cmd_audit_dist(paths), 2)

    def test_dist_with_persona_member_in_targz_fails(self) -> None:
        with TemporaryDirectory() as t:
            root = Path(t)
            (root / "dist").mkdir()
            tgz = root / "dist" / "dotpanel-x.tar.gz"
            with tarfile.open(tgz, "w:gz") as tf:
                # Add a clean file
                clean_path = root / "ok.md"
                clean_path.write_text("ok")
                tf.add(clean_path, arcname="dotpanel-x/ok.md")
                # Add persona leak
                leak_path = root / "leak.md"
                leak_path.write_text("leak")
                tf.add(leak_path, arcname="dotpanel-x/persona/leak.md")
            paths = DotpanelPaths(root=root, home=root)
            with redirect_stdout(StringIO()), redirect_stderr(StringIO()):
                self.assertEqual(cmd_audit_dist(paths), 2)

    def test_dist_clean_passes(self) -> None:
        with TemporaryDirectory() as t:
            root = Path(t)
            (root / "dist").mkdir()
            whl = root / "dist" / "dotpanel-x-py3-none-any.whl"
            with zipfile.ZipFile(whl, "w") as zf:
                zf.writestr("dotpanel/__init__.py", "x = 1\n")
                zf.writestr("dotpanel/cli.py", "y = 2\n")
            paths = DotpanelPaths(root=root, home=root)
            with redirect_stdout(StringIO()):
                self.assertEqual(cmd_audit_dist(paths), 0)


