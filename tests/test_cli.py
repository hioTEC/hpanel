class ConfigureTests(unittest.TestCase):
    def test_configure_all_renders_kimi_startup_adapter(self) -> None:
        with TemporaryDirectory() as t:
            root = dotpanel_root()
            home = Path(t) / "home"
            output = Path(t) / "render"
            home.mkdir()
            paths = DotpanelPaths(root=root, home=home)
            with redirect_stdout(StringIO()):
                self.assertEqual(cmd_configure(paths, "all", False, False, False, output), 0)
            kimi_agents = output / "kimi" / "AGENTS.md"
            self.assertTrue(kimi_agents.exists())
            content = kimi_agents.read_text()
            self.assertIn(f"{root}/persona/voice.md", content)
            self.assertIn(f"{root}/protocol/workspace.md", content)
            self.assertIn(GENERATED_BANNER, content)

    def test_configure_codex_renders_env_key_profiles(self) -> None:
        with TemporaryDirectory() as t:
            root = dotpanel_root()
            home = Path(t) / "home"
            output = Path(t) / "render"
            home.mkdir()
            paths = DotpanelPaths(root=root, home=home)
            with redirect_stdout(StringIO()):
                self.assertEqual(cmd_configure(paths, "codex", False, False, False, output), 0)
            config = output / "codex" / "config.toml"
            self.assertTrue(config.exists())
            content = config.read_text()
            self.assertIn('model_provider = "openai"', content)
            self.assertIn("[profiles.andy]", content)
            self.assertIn('model_provider = "andyfeng"', content)
            self.assertIn("[profiles.let]", content)
            self.assertIn('model_provider = "letaicode"', content)
            self.assertIn('env_key = "ANDYFENG_CODEX_KEY"', content)
            self.assertIn('env_key = "LETAICODE_CODEX_KEY"', content)
            self.assertNotIn("api_key =", content)

    def test_configure_codex_renders_default_permission_rules(self) -> None:
        with TemporaryDirectory() as t:
            root = dotpanel_root()
            home = Path(t) / "home"
            output = Path(t) / "render"
            home.mkdir()
            paths = DotpanelPaths(root=root, home=home)
            with redirect_stdout(StringIO()):
                self.assertEqual(cmd_configure(paths, "codex", False, False, False, output), 0)
            rules = output / "codex" / "rules" / "default.rules"
            self.assertTrue(rules.exists())
            content = rules.read_text()
            self.assertIn("Generated by dotpanel", content)
            self.assertIn('prefix_rule(pattern=["git"], decision="allow")', content)
            self.assertIn('prefix_rule(pattern=["python3", "-m", "unittest"], decision="allow")', content)

    def test_codex_only_default_rules_escape_excluded_rules_dir(self) -> None:
        self.assertFalse(_excluded_path("rules/default.rules", "codex"))
        self.assertTrue(_excluded_path("rules/custom.rules", "codex"))


