"""Phase C12: managed-skills registry + --prune-orphan-skills.

Tests cover:
- Registry is written on each `configure` run (~/.dotpanel/managed-skills.json)
- Registry schema (skills + harnesses + written_at)
- --prune-orphan-skills removes banner-marked dirs not in registry
- Prune skips dirs without dotpanel banner (user-created skills protected)
- Dry-run mode prints WOULD-PRUNE without deleting
- C12 dot -> sync rename: cli.py registries renamed; render produces sync wrapper
"""
from __future__ import annotations

import contextlib
import io
